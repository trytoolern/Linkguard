import { test } from 'node:test';
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { checkInBrowser, readRenderedPage, type BrowserCheckApi } from '../lib/browser-check.ts';
import type { RenderedPage } from '../lib/rendered-page.ts';
import type { Result } from '../lib/types.ts';
const row: Result = { url: 'https://example.com/app', kind: 'internal', count: 1, status: 200, finalUrl: 'https://example.com/app', method: 'GET', elapsed: 10, outcome: 'uncertain', error: 'Needs browser check', mode: 'deep', reason: 'needs-browser', contentState: 'needs-browser' };
const page: RenderedPage = { url: row.url, title: 'Dashboard', heading: 'Your dashboard', text: 'Here is the useful content generated by this application.', script: true, password: false, media: false, form: false, truncated: false };
function fixture(snapshot: () => Promise<RenderedPage> = async () => page) {
  const removed: number[] = []; const created: object[] = [];
  const api: BrowserCheckApi = {
    tabs: { async create(options) { created.push(options); return { id: 900 }; }, async get() { return { url: row.url, status: 'complete', active: false }; }, async remove(id) { removed.push(id); } }, snapshot,
  };
  return { api, removed, created };
}
const timing = { budgetMs: 1000, intervalMs: 1 };
test('waits for generated content, confirms stable evidence, closes only its own inactive tab', async () => {
  let reads = 0;
  const f = fixture(async () => ++reads < 3 ? { ...page, text: 'Loading…', heading: '' } : { ...page, text: `${page.text} Count: ${reads}` });
  const result = await checkInBrowser(f.api, row, new AbortController().signal, 4, timing);
  assert.equal(result.outcome, 'ok'); assert.equal(result.contentState, 'present'); assert.equal(result.browserChecked, true);
  assert.equal(result.status, null, 'Do not invent a network status for browser navigation');
  assert.ok(reads >= 5); assert.deepEqual(f.created, [{ url: row.url, active: false, windowId: 4 }]); assert.deepEqual(f.removed, [900]);
  assert.equal(row.reason, 'needs-browser', 'Do not mutate cached input');
});
test('browser-rendered challenge and error pages never become green', async () => {
  for (const [title, text, expected] of [['Just a moment', 'Verify you are human.', 'restricted'], ['404 Not found', 'Sorry, the requested page is missing.', 'uncertain']]) {
    const f = fixture(async () => ({ ...page, title: title!, heading: title!, text: text! }));
    const result = await checkInBrowser(f.api, row, new AbortController().signal, undefined, timing);
    assert.equal(result.outcome, expected); assert.deepEqual(f.removed, [900]);
  }
});
test('timeouts keep uncertain evidence and close the temporary tab', async () => {
  const f = fixture(async () => ({ ...page, text: '', heading: '' }));
  const result = await checkInBrowser(f.api, row, new AbortController().signal, undefined, { budgetMs: 25, intervalMs: 1 });
  assert.equal(result.outcome, 'uncertain'); assert.equal(result.browserChecked, undefined); assert.deepEqual(f.removed, [900]);
});
test('cancellation closes an owned tab; an activated tab is left to the user', async () => {
  const controller = new AbortController();
  const f = fixture(async () => { controller.abort(); return page; });
  await assert.rejects(checkInBrowser(f.api, row, controller.signal, undefined, timing)); assert.deepEqual(f.removed, [900]);
  const active = fixture(); active.api.tabs.get = async () => ({ url: row.url, active: true });
  assert.equal((await checkInBrowser(active.api, row, new AbortController().signal, undefined, timing)).outcome, 'uncertain');
  assert.deepEqual(active.removed, []);
});
test('late tab creation after cancellation is cleaned up without touching existing tabs', async () => {
  const f = fixture(); const controller = new AbortController();
  let finish!: (tab: {id:number}) => void;
  f.api.tabs.create = () => new Promise(resolve => { finish = resolve; });
  const pending = checkInBrowser(f.api, row, controller.signal, undefined, timing);
  controller.abort(); await assert.rejects(pending); finish({ id: 901 });
  await new Promise(resolve => setTimeout(resolve, 5)); assert.deepEqual(f.removed, [901]);
});
test('injected function reads generated DOM and excludes CSS-hidden text without executing page scripts', async () => {
  const window = new Window({ url: row.url, settings: { enableJavaScriptEvaluation: true, suppressInsecureJavaScriptEnvironmentWarning: true } });
  try {
    window.document.body.innerHTML = '<style>.hidden{display:none}</style><nav>Navigation is not content</nav><main><h1><span class="hidden">404 Not found</span>Dashboard</h1><p>Real generated content from the application is here.</p></main><script>throw new Error("must not execute")</script>';
    const snapshot = window.eval(`(${readRenderedPage.toString()})()`);
    assert.ok(snapshot.text.includes('Real generated content')); assert.ok(!snapshot.text.includes('Navigation')); assert.ok(!snapshot.text.includes('404'));
    assert.equal(snapshot.heading, 'Dashboard'); assert.equal(snapshot.url, row.url);
  } finally { await window.happyDOM.abort(); }
});

test('preserves the source Firefox container and original HTTP evidence', async () => {
  const f = fixture(); f.api.response = () => ({ url: row.url, status: 200 });
  const result = await checkInBrowser(f.api, { ...row, status: 403 }, new AbortController().signal, 4, timing, 'firefox-container-2');
  assert.equal(result.status, 200); assert.equal(result.httpStatus, 403); assert.equal(result.outcome, 'ok');
  assert.equal((f.created[0] as any).cookieStoreId, 'firefox-container-2');
});

test('real navigation HTTP failures override visible content; absent navigation evidence cannot erase an HTTP failure', async () => {
  for (const status of [404,410,403,429,503]) {
    const f = fixture(); f.api.response = () => ({ url: row.url, status });
    const result = await checkInBrowser(f.api, row, new AbortController().signal, undefined, timing);
    assert.notEqual(result.outcome, 'ok'); assert.equal(result.status, status); assert.equal(result.reason, status >= 500 ? 'server-error' : 'http');
  }
  const f = fixture();
  assert.equal((await checkInBrowser(f.api, { ...row, status: 404 }, new AbortController().signal, undefined, timing)).outcome, 'uncertain');
  f.api.response = () => ({ url: 'https://example.com/another-document', status: 200 });
  assert.equal((await checkInBrowser(f.api, { ...row, status: 404 }, new AbortController().signal, undefined, timing)).status, null);
});

test('a failed render cannot leave static HTML green', async () => {
  const f = fixture(async () => ({ ...page, text: '', heading: '', script: false }));
  const result = await checkInBrowser(f.api, { ...row, outcome: 'ok', contentState: 'present', reason: 'content-found' }, new AbortController().signal, undefined, { budgetMs: 20, intervalMs: 1 });
  assert.equal(result.outcome, 'uncertain'); assert.equal(result.reason, 'timeout'); assert.equal(result.browserChecked, undefined);
});

test('equally long changing text is not stable; busy main content is not ready', async () => {
  let n = 0;
  const f = fixture(async () => ({ ...page, text: ++n % 2 ? 'The first changing version of this page.' : 'The other changing version of this page.' }));
  const result = await checkInBrowser(f.api, row, new AbortController().signal, undefined, { budgetMs: 25, intervalMs: 1 });
  assert.equal(result.browserChecked, undefined);
  const busy = fixture(async () => ({ ...page, busy: true }));
  assert.equal((await checkInBrowser(busy.api, row, new AbortController().signal, undefined, { budgetMs: 25, intervalMs: 1 })).browserChecked, undefined);
});

test('DOM discovery respects base URL, open shadow roots, downloads, and main-content priority', async () => {
  const window = new Window({ url: row.url, settings: { enableJavaScriptEvaluation: true, suppressInsecureJavaScriptEnvironmentWarning: true } });
  try {
    window.document.head.innerHTML = '<base href="https://example.com/docs/">';
    window.document.body.innerHTML = '<aside>A very long sidebar which must not hide an empty application.</aside><main aria-busy="true">Loading…</main><nav><a href="guide">Guide</a><a href="file" download>Download</a></nav><div id="host"></div>';
    window.document.querySelector('#host')!.attachShadow({ mode: 'open' }).innerHTML = '<a href="shadow">Shadow</a>';
    const snapshot = window.eval(`(${readRenderedPage.toString()})()`);
    assert.equal(snapshot.text, 'Loading…'); assert.equal(snapshot.busy, true);
    assert.deepEqual([...snapshot.links], ['https://example.com/docs/guide','https://example.com/docs/shadow']);
  } finally { await window.happyDOM.abort(); }
});

test('an empty main region cannot become green because of sidebar text', async () => {
  const window = new Window({ url: row.url, settings: { enableJavaScriptEvaluation: true, suppressInsecureJavaScriptEnvironmentWarning: true } });
  try {
    for (const markup of ['<main></main>', '<div style="display:none"><main>Hidden main content is long enough to look like real content.</main></div>', '<main style="height:0;overflow:hidden">Clipped content should never prove a page works.</main>']) {
      window.document.body.innerHTML = `<aside>A long sidebar full of text which is not the requested document.</aside>${markup}`;
      const snapshot = window.eval(`(${readRenderedPage.toString()})()`);
      assert.equal(snapshot.text, '', markup);
    }
  } finally { await window.happyDOM.abort(); }
});
